#!/usr/bin/env python3
"""Generate public Goldilocks compiler tables; no witness-dependent inputs."""

import argparse
from pathlib import Path

MODULUS = 0xFFFFFFFF00000001
# p3-goldilocks 0.6.1 Goldilocks::TWO_ADIC_GENERATORS[32]. Rust tests
# independently compare every derived root with the field implementation.
ROOT_32 = 0x185629DCDA58878C
DESTINATION = Path(__file__).resolve().parents[1] / (
    "src/block_v2/gpu_hash/engine/device/compiler_constants/tables.cl"
)


def render():
    inverse_roots = [pow(pow(ROOT_32, 1 << (32 - log), MODULUS), -1, MODULUS)
                     for log in range(33)]
    inverse_factorials = [1]
    for n in range(1, 64):
        inverse_factorials.append(inverse_factorials[-1] * pow(n, -1, MODULUS) % MODULUS)
    root = pow(ROOT_32, 1 << 27, MODULUS)
    reciprocal_differences = [0] + [
        pow((pow(root, n, MODULUS) - 1) % MODULUS, -1, MODULUS)
        for n in range(1, 32)
    ]
    text = ("// Generated by scripts/generate-compiler-constant-tables.py.\n"
            "// Public constants only; GPU tests check the independent CPU formulas.\n")
    for name, values in [
        ("compiler_inverse_roots", inverse_roots),
        ("compiler_inverse_factorials", inverse_factorials),
        ("compiler_reciprocal_differences", reciprocal_differences),
        ("compiler_inverse_coset", [pow(7, -1, MODULUS)]),
    ]:
        text += f"__constant ulong {name}[{len(values)}] = {{\n"
        for offset in range(0, len(values), 4):
            text += "    " + ", ".join(f"0x{v:016x}UL" for v in values[offset:offset + 4]) + ",\n"
        text += "};\n"
    return text


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if DESTINATION.read_text() != generated:
            parser.error("compiler tables differ; regenerate without --check")
    else:
        DESTINATION.write_text(generated)
