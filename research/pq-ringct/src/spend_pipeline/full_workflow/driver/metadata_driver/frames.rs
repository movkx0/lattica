fn sum(parts: impl IntoIterator<Item = usize>) -> Result<usize> {
    parts.into_iter().try_fold(0usize, |total, part| {
        total.checked_add(part.checked_mul(8).ok_or(WorkflowError::Overflow)?)
            .ok_or(WorkflowError::Overflow)
    })
}
fn table_borrows<T: 'static>() -> Result<usize> {
    sum([size_of::<&CaseOwnerTable<'static, T>>(),
        size_of::<Result<&CaseOwnerTable<'static, T>>>(),
        size_of::<&CaseOwnerSlot<'static, T>>(),
        size_of::<Result<&CaseOwnerSlot<'static, T>>>()])
}

