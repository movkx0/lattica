#!/usr/bin/env python3
"""Generate source-qualified native numeric bounds from a guarded CPU profile."""
from numeric_source_inputs import select_receipt
import argparse
import hashlib
import json
from pathlib import Path
from native_metadata_profile import validate
from opencl_private_spend_validate import ROOT, require, sha, source_manifest

DESTINATION = 'research/pq-ringct/src/component_tree/native_shape/precomputed/data.rs'
REGISTERED = 'lattica-prover-p3/src/block_v2/machine/verifier/batch/shape/precomputed/data.rs'
TEST = 'component_tree::native_shape::profiling::tests::native_metadata_profile'

def verified(path):
    record = json.loads(path.read_text())
    require(record.get('status') == 'passed' and record.get('native_metadata_profile') is True
            and record.get('source_inputs_unchanged') is True and record.get('executable_unchanged') is True
            and record.get('all_subprocesses_terminal_and_reaped') is True and record.get('service_stop_completed') is True,
            'native qualification did not finish cleanly')
    command = record.get('command', [])
    require(len(command) == 6 and command[1:] == [TEST, '--exact', '--ignored', '--test-threads=1', '--nocapture']
            and record.get('expect_tests') is True, 'wrong native qualification selector')
    log = Path(record['raw_log'])
    require(sha(log) == record.get('raw_log_sha256'), 'native qualification log changed')
    provenance = record['executable_provenance']
    build_path = Path(provenance['build_record'])
    require(sha(build_path) == provenance['build_record_sha256'], 'native build record changed')
    build = json.loads(build_path.read_text())
    require(build.get('status') == 'passed' and build.get('input_sha256') == record.get('input_sha256'),
            'native binary is not bound to these sources')
    select = lambda files: select_receipt(files, native=True)
    require(select(record['input_sha256']) == select(source_manifest()), 'sources changed; requalify native tables')
    accepted = validate(log.read_text())
    require(accepted.get('identity') is not None and len(accepted.get('cohorts', [])) == 5,
            'missing native table provenance or worker qualification')
    return accepted

def render(accepted):
    identity = accepted['identity']
    rows = sorted(accepted['rows'], key=lambda row: row['descriptor_key'])
    digest = hashlib.sha3_256(b'ringct/native-numeric-table/v1\0')
    digest.update(bytes(identity['source']))
    digest.update(bytes(identity['profile']))
    digest.update(len(rows).to_bytes(8, 'little'))
    for row in rows:
        digest.update(bytes(row['descriptor_key']))
        for value in row['geometry'] + row['values']: digest.update(value.to_bytes(8, 'little'))
    array = lambda values: '[' + ', '.join(str(v) for v in values) + ']'
    lines = ['// Generated by research/pq-ringct/tools/generate_native_metadata_tables.py.',
             '// Exact descriptor bounds; runtime source/profile/content and preflight checks are mandatory.',
             'use super::Row;',
             'pub(super) const SOURCE: [u8; 32] = ' + array(identity['source']) + ';',
             'pub(super) const PROFILE: [u8; 32] = ' + array(identity['profile']) + ';',
             'pub(super) const CONTENT: [u8; 32] = ' + array(digest.digest()) + ';',
             'pub(super) const ROWS: &[Row] = &[']
    for row in rows:
        lines.append('    Row { key: %s, geometry: %s, values: %s },' %
                     (array(row['descriptor_key']), array(row['geometry']), array(row['values'])))
    return '\n'.join(lines + ['];', ''])

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--record', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    accepted = verified(args.record)
    rendered = render(accepted)
    target = ROOT / DESTINATION
    if args.check: require(target.read_text() == rendered, 'native table differs from qualification')
    else: target.write_text(rendered)
    print(json.dumps(dict(path=str(target), checked=args.check, rows=len(accepted['rows']))))

if __name__ == '__main__': main()
