#!/usr/bin/env python3
"""Generate fixed registered numeric tables from a passed, source-bound guard run."""
from numeric_source_inputs import select_receipt
import argparse
import hashlib
import json
from pathlib import Path
from metadata_cpu_qualification import validate
from opencl_private_spend_validate import ROOT, require, sha, source_manifest

DESTINATION = 'lattica-prover-p3/src/block_v2/machine/verifier/batch/shape/precomputed/data.rs'
TEST = 'block_v2::machine::verifier::batch::shape::metadata_planning::tests::metadata_cpu_worker_qualification'

def verified(record_path):
    record = json.loads(record_path.read_text())
    require(record.get('status') == 'passed' and record.get('profile') == 'research-compile-large'
            and record.get('source_inputs_unchanged') is True and record.get('executable_unchanged') is True
            and record.get('all_subprocesses_terminal_and_reaped') is True
            and record.get('service_stop_completed') is True, 'qualification did not finish cleanly')
    command = record.get('command', [])
    require(len(command) == 6 and command[1:] == [TEST, '--exact', '--ignored', '--test-threads=1', '--nocapture']
            and record.get('expect_tests') is True, 'wrong qualification selector')
    log = Path(record['raw_log'])
    require(sha(log) == record.get('raw_log_sha256'), 'qualification log changed')
    provenance = record['executable_provenance']
    build_path = Path(provenance['build_record'])
    require(sha(build_path) == provenance['build_record_sha256'], 'build record changed')
    build = json.loads(build_path.read_text())
    require(build.get('status') == 'passed' and build.get('input_sha256') == record.get('input_sha256'),
            'qualifying binary is not bound to these sources')
    # Current core source inventory must match the qualified build. Only the
    # generated table is excluded, so adding/removing a core source also fails.
    select = lambda files: select_receipt(files, native=False)
    require(select(record['input_sha256']) == select(source_manifest()), 'core sources changed; requalify before generating tables')
    return validate(log.read_text())['tables']

def render(tables):
    identity, rows = tables['identity'], tables['rows']
    digest = hashlib.sha3_256(b'lattica/qualified-numeric-planning-rows/v1\0')
    for row in rows:
        for value in [row['public_values'], row['log_height'], *row['values']]: digest.update(value.to_bytes(8, 'little'))
    array = lambda values: '[' + ', '.join(str(v) for v in values) + ']'
    lines = ['// Generated by research/pq-ringct/tools/generate_metadata_tables.py.',
             '// Qualified numeric bounds only; runtime source/profile/content checks are mandatory.',
             'use super::Row;',
             'pub(super) const SOURCE_DIGEST: [u8; 32] = ' + array(identity['source_digest']) + ';',
             'pub(super) const PROFILE_ID: [u8; 32] = ' + array(identity['profile_id']) + ';',
             'pub(super) const SIGNATURE: [usize; 12] = ' + array(identity['signature']) + ';',
             'pub(super) const ROWS_DIGEST: [u8; 32] = ' + array(digest.digest()) + ';',
             'pub(super) const ROWS: &[Row] = &[']
    for row in rows:
        lines.append('    Row { public_values: %d, log_height: %d, values: %s },' %
                     (row['public_values'], row['log_height'], array(row['values'])))
    return '\n'.join(lines + ['];', ''])

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--record', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = render(verified(args.record))
    target = ROOT / DESTINATION
    if args.check:
        require(target.read_text() == text, 'generated metadata table differs from qualification')
    else:
        target.write_text(text)
    print(json.dumps(dict(path=str(target), checked=args.check, rows=72)))

if __name__ == '__main__': main()
